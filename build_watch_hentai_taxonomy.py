import json
import os

with open('watch_hentai_harvest.json', 'r', encoding='utf-8') as f:
    data = json.load(f)

def escape_str(s):
    if not s:
        return ''
    return s.replace('\\', '\\\\').replace('"', '\\"').replace('$', '\\$')

lines = []
lines.append('// GENERATED LIVE TAXONOMY FOR WATCHHENTAI (watchhentai.net)')
lines.append('// Harvested live via Scrapling from https://watchhentai.net/series/, /genre/, /videos/')
lines.append(f'// Total Categories & Serialized Series: {len(data["categories"])}')
lines.append(f'// Total Genres & Tags: {len(data["genres"])}')
lines.append(f'// Total Series Covers: {len(data["series_covers"])}')
lines.append(f'// Total Genre Covers: {len(data["genre_covers"])}')
lines.append("import 'package:flutter/material.dart';")
lines.append("import '../../models/catalog_model.dart';")
lines.append('')
lines.append('/// Companion cover posters for serialized anime series harvested live from WatchHentai')
lines.append('final Map<String, String> watchHentaiSeriesCovers = const {')
for slug, cover in sorted(data['series_covers'].items()):
    lines.append(f'  "{escape_str(slug)}": "{escape_str(cover)}",')
lines.append('};')
lines.append('')
lines.append('/// Companion cover posters for genres harvested live from WatchHentai')
lines.append('final Map<String, String> watchHentaiGenreCovers = const {')
for slug, cover in sorted(data['genre_covers'].items()):
    lines.append(f'  "{escape_str(slug)}": "{escape_str(cover)}",')
lines.append('};')
lines.append('')
lines.append('/// Combined companion cover posters for WatchHentai Explore catalog')
lines.append('final Map<String, String> watchHentaiCovers = const {')
for slug, cover in sorted(data['combined_covers'].items()):
    lines.append(f'  "{escape_str(slug)}": "{escape_str(cover)}",')
lines.append('};')
lines.append('')
lines.append('/// Authentic WatchHentai Categories and Serialized Anime Series')
lines.append('final List<CatalogItem> watchHentaiCategories = const [')
for cat in data['categories']:
    name = escape_str(cat['name'])
    slug = escape_str(cat['slug'])
    group = escape_str(cat.get('categoryGroup', 'Category'))
    icon = cat.get('icon', 'Icons.category_rounded')
    count = cat.get('count', 0)
    desc = escape_str(cat.get('description', ''))
    endpoint = escape_str(cat.get('endpointPath', ''))

    lines.append('  CatalogItem(')
    lines.append(f'    name: "{name}",')
    lines.append(f'    slug: "{slug}",')
    lines.append('    type: CatalogType.category,')
    lines.append(f'    categoryGroup: "{group}",')
    lines.append(f'    icon: {icon},')
    lines.append(f'    count: {count},')
    lines.append(f'    description: "{desc}",')
    lines.append(f'    endpointPath: "{endpoint}",')
    lines.append('  ),')
lines.append('];')
lines.append('')
lines.append('/// Authentic WatchHentai Genres and Tags harvested live')
lines.append('final List<CatalogItem> watchHentaiGenres = const [')
for g in data['genres']:
    name = escape_str(g['name'])
    slug = escape_str(g['slug'])
    group = escape_str(g.get('categoryGroup', 'Genre'))
    icon = g.get('icon', 'Icons.tag_rounded')
    count = g.get('count', 0)
    desc = escape_str(g.get('description', ''))
    endpoint = escape_str(g.get('endpointPath', f'/genre/{slug}/'))

    lines.append('  CatalogItem(')
    lines.append(f'    name: "{name}",')
    lines.append(f'    slug: "{slug}",')
    lines.append('    type: CatalogType.genre,')
    lines.append(f'    categoryGroup: "{group}",')
    lines.append(f'    icon: {icon},')
    lines.append(f'    count: {count},')
    lines.append(f'    description: "{desc}",')
    lines.append(f'    endpointPath: "{endpoint}",')
    lines.append('  ),')
lines.append('];')
lines.append('')
lines.append('/// Master ExtensionTaxonomy for WatchHentai with dynamic Categories (grid) and Genres (tags)')
lines.append('final ExtensionTaxonomy watchHentaiTaxonomy = ExtensionTaxonomy(')
lines.append('  sections: [')
lines.append('    TaxonomySection(')
lines.append('      id: "categories",')
lines.append('      title: "Categories",')
lines.append('      displayType: TaxonomyDisplayType.grid,')
lines.append('      items: watchHentaiCategories,')
lines.append('      icon: Icons.category_rounded,')
lines.append('    ),')
lines.append('    TaxonomySection(')
lines.append('      id: "genres",')
lines.append('      title: "Genres & Tags",')
lines.append('      displayType: TaxonomyDisplayType.tags,')
lines.append('      items: watchHentaiGenres,')
lines.append('      icon: Icons.tag_rounded,')
lines.append('    ),')
lines.append('  ],')
lines.append('  categories: watchHentaiCategories,')
lines.append('  tagsAndGenres: watchHentaiGenres,')
lines.append('  artists: const [],')
lines.append(');')
lines.append('')

out_path = os.path.join('lib', 'extensions', 'taxonomies', 'watch_hentai_taxonomy.dart')
with open(out_path, 'w', encoding='utf-8') as f:
    f.write('\n'.join(lines))

print(f'Successfully wrote {len(lines)} lines to {out_path}')

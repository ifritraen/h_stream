import json
import re

# 1. GENERATE HENTAIDB TAXONOMY
with open("scratch/hentaidb_harvest.json", "r", encoding="utf-8") as f:
    hdb_data = json.load(f)

hdb_series = hdb_data['series']
hdb_tags = hdb_data['tags']

hdb_dart = []
hdb_dart.append("// HentaiDB Dynamic Taxonomy")
hdb_dart.append("// Auto-generated from official HentaiDB live discovery.")
hdb_dart.append("import 'package:flutter/material.dart';")
hdb_dart.append("import '../../models/catalog_model.dart';")
hdb_dart.append("")
hdb_dart.append("/// Series cover thumbnail artwork map")
hdb_dart.append("const Map<String, String> hentaiDbSeriesCovers = {")
for s in hdb_series:
    slug = s['slug'].replace('"', '\\"')
    cover = s['cover'].replace('"', '\\"')
    hdb_dart.append(f'  "{slug}": "{cover}",')
hdb_dart.append("};")
hdb_dart.append("")
hdb_dart.append("/// HentaiDB indexed anime series catalog (80 top series)")
hdb_dart.append("final List<CatalogItem> hentaiDbSeries = [")
for s in hdb_series:
    name = s['name'].replace('"', '\\"').replace('$', '\\$')
    slug = s['slug'].replace('"', '\\"')
    path = s['endpointPath'].replace('"', '\\"')
    hdb_dart.append("  CatalogItem(")
    hdb_dart.append(f'    name: "{name}",')
    hdb_dart.append(f'    slug: "{slug}",')
    hdb_dart.append("    type: CatalogType.category,")
    hdb_dart.append("    categoryGroup: 'Series',")
    hdb_dart.append("    icon: Icons.video_library_rounded,")
    hdb_dart.append(f'    endpointPath: "{path}",')
    hdb_dart.append("  ),")
hdb_dart.append("];")
hdb_dart.append("")
hdb_dart.append(f"/// HentaiDB tags and tropes ({len(hdb_tags)} indexed)")
hdb_dart.append("final List<CatalogItem> hentaiDbTags = [")
for t in hdb_tags:
    t_clean = t.replace('"', '\\"').replace('$', '\\$')
    t_slug = re.sub(r'[^a-zA-Z0-9]+', '-', t.lower()).strip('-')
    hdb_dart.append("  CatalogItem(")
    hdb_dart.append(f'    name: "{t_clean}",')
    hdb_dart.append(f'    slug: "{t_slug}",')
    hdb_dart.append("    type: CatalogType.tag,")
    hdb_dart.append("    categoryGroup: 'Tags',")
    hdb_dart.append("    icon: Icons.tag_rounded,")
    hdb_dart.append(f'    endpointPath: "/?tag={t_clean}",')
    hdb_dart.append("  ),")
hdb_dart.append("];")
hdb_dart.append("")
hdb_dart.append("/// Dynamic ExtensionTaxonomy for HentaiDB")
hdb_dart.append("final ExtensionTaxonomy hentaiDbTaxonomy = ExtensionTaxonomy(")
hdb_dart.append("  sections: [")
hdb_dart.append("    TaxonomySection(")
hdb_dart.append('      id: "series",')
hdb_dart.append(f'      title: "Popular Anime Series ({len(hdb_series)})",')
hdb_dart.append("      displayType: TaxonomyDisplayType.grid,")
hdb_dart.append("      items: hentaiDbSeries,")
hdb_dart.append("    ),")
hdb_dart.append("    TaxonomySection(")
hdb_dart.append('      id: "tags",')
hdb_dart.append(f'      title: "Tags & Tropes ({len(hdb_tags)})",')
hdb_dart.append("      displayType: TaxonomyDisplayType.tags,")
hdb_dart.append("      items: hentaiDbTags,")
hdb_dart.append("    ),")
hdb_dart.append("  ],")
hdb_dart.append(");")
hdb_dart.append("")

with open("lib/extensions/taxonomies/hentaidb_taxonomy.dart", "w", encoding="utf-8") as f:
    f.write("\n".join(hdb_dart))
print("Generated lib/extensions/taxonomies/hentaidb_taxonomy.dart successfully!")


